def seed_initial_items(db: Session) -> None:
    created_any = False
    for item_data in INITIAL_ITEM_TEMPLATES:
        if get_item_template_by_name(db, str(item_data["name"])):
            continue
        create_item_template(db, item_data)
        created_any = True
    if created_any:
        db.commit()


def seed_initial_mission_drops(db: Session) -> None:
    created_any = False
    for mission_name, item_name, chance, min_quantity, max_quantity in INITIAL_MISSION_DROPS:
        mission = get_mission_template_by_name(db, mission_name)
        item = get_item_template_by_name(db, item_name)
        if mission is None or item is None:
            continue
        if get_mission_drop_by_pair(db, mission.id, item.id):
            continue
        create_mission_drop(
            db,
            {
                "mission_template_id": mission.id,
                "item_template_id": item.id,
                "drop_chance": chance,
                "min_quantity": min_quantity,
                "max_quantity": max_quantity,
                "is_active": True,
            },
        )
        created_any = True
    if created_any:
        db.commit()
